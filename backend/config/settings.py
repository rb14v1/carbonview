class _AzureInternalHostMiddleware:
    """Allow Azure internal probe hosts that reach the app by link-local/private IP."""

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        raw_host = request.META.get("HTTP_HOST", "")
        if _is_app_service_mode() and _allow_internal_probe_hosts(raw_host):
            request.META["HTTP_HOST"] = website_hostname or "localhost"
        return self.get_response(request)


