def _parse_connection_string(connection_string):
    parts = {}
    for segment in str(connection_string or "").split(";"):
        segment = segment.strip()
        if not segment or "=" not in segment:
            continue
        key, value = segment.split("=", 1)
        parts[key.strip()] = value.strip()
    return parts


def _validate_azure_storage_connection_string(connection_string):
    normalized = str(connection_string or "").strip()
    if not normalized:
        return False, "missing connection string"

    parts = _parse_connection_string(normalized)
    account_name = parts.get("AccountName", "")
    account_key = parts.get("AccountKey", "")
    if not account_name:
        return False, "missing AccountName in AZURE_STORAGE_CONNECTION_STRING"
    if not account_key:
        return False, "missing AccountKey in AZURE_STORAGE_CONNECTION_STRING"

    try:
        base64.b64decode(account_key, validate=True)
    except (binascii.Error, ValueError):
        return False, "invalid AccountKey base64 in AZURE_STORAGE_CONNECTION_STRING"
    return True, ""


def _is_azure_postgres_host(hostname):
    normalized = str(hostname or "").strip().lower()
    return normalized.endswith(".postgres.database.azure.com")


def _is_app_service_mode():
    return bool(
        os.getenv("WEBSITE_HOSTNAME")
        or os.getenv("WEBSITE_SITE_NAME")
        or os.getenv("WEBSITE_INSTANCE_ID")
    )


def _allow_internal_probe_hosts(host):
    normalized = str(host or "").strip()
    if not normalized:
        return False
    if ":" in normalized and normalized.count(":") == 1:
        normalized = normalized.split(":", 1)[0]
    try:
        ip = ipaddress.ip_address(normalized)
    except ValueError:
        return False
    return ip.is_private or ip.is_link_local or ip.is_loopback


